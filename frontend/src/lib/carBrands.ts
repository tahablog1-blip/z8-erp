/** تطبيع الاسم: حروف صغيرة، همزات/ى/ة موحّدة، بدون مسافات أو رموز */
export function normalizeBrand(s: string): string {
  return s.toLowerCase()
    .replace(/[أإآ]/g, "ا").replace(/ى/g, "ي").replace(/ة/g, "ه")
    .replace(/[^a-z0-9\u0600-\u06FF]+/g, "");
}

const INDEX: Record<string, string> = (() => {
  const idx: Record<string, string> = {};
  for (const slug of Object.keys(FILES)) idx[normalizeBrand(slug)] = slug;
  for (const [alias, slug] of Object.entries(ALIASES)) idx[normalizeBrand(alias)] = slug;
  return idx;
})();

/** مسار لوجو الماركة، أو null لو مش معروفة */
export function brandLogoSrc(brand: string | null | undefined): string | null {
  if (!brand) return null;
  const slug = INDEX[normalizeBrand(brand)];
  return slug ? `/brands/${slug}.${FILES[slug]}` : null;
}
